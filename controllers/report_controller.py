import csv
from datetime import date, timedelta
from io import StringIO

from flask import Blueprint, Response, render_template, request

from models import report_model

report_bp = Blueprint("report", __name__)


def _range():
    to_date = request.args.get("to_date") or date.today().isoformat()
    from_date = request.args.get("from_date") or (date.today() - timedelta(days=30)).isoformat()
    return from_date, to_date


def _csv_download(filename, headers, rows, keys):
    buf = StringIO()
    writer = csv.writer(buf)
    writer.writerow(headers)
    for row in rows:
        writer.writerow(["" if row.get(k) is None else str(row.get(k)) for k in keys])
    return Response(
        buf.getvalue(),
        mimetype="text/csv; charset=utf-8",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


def _show(title, filename, headers, rows, keys, from_date, to_date, show_dates=True):
    if request.args.get("export") == "csv":
        return _csv_download(filename, headers, rows, keys)
    return render_template(
        "reports/table.html",
        title=title,
        from_date=from_date,
        to_date=to_date,
        headers=headers,
        rows=rows,
        keys=keys,
        show_dates=show_dates,
    )


@report_bp.route("/reports")
def index():
    from_date, to_date = _range()
    return render_template("reports/index.html", from_date=from_date, to_date=to_date)


@report_bp.route("/reports/sales")
def sales():
    from_date, to_date = _range()
    return _show(
        "Sales report",
        "sales-report.csv",
        ["Invoice", "Date", "Customer", "Generated by", "Discount %", "GST", "Total", "Sale Status", "Payment"],
        report_model.sales_report(from_date, to_date),
        ["invoice_no", "sale_date", "customer_name", "generated_by", "discount", "gst_amount", "total_amount", "sale_status", "payment_status"],
        from_date,
        to_date,
    )


